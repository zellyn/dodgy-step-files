"""A097 — Error transferring .stp from STEPCAFControl_Reader to OCAF document.

Catalog claim: two distinct APPLICATION_CONTEXT records with the same
string content; parser accepts, but STEPCAFControl_Reader::Transfer
returns false because the chain walks fail to match.

Previous fixture used empty-EDGE_LOOP placeholders. Regen: one real
face + 2 explicit APPLICATION_CONTEXT records with identical string
content but distinct entity IDs.
"""
from step_corpus.step_builder import StepFile

f = StepFile(catalog_id="A097",
             defect="2 distinct APPLICATION_CONTEXT records with same string content")

orig = f.cartesian_point((0.0, 0.0, 0.0))
zdir = f.direction((0.0, 0.0, 1.0))
xdir = f.direction((1.0, 0.0, 0.0))
plc = f.axis2_placement_3d(orig, zdir, xdir)
plane = f.plane(plc)

def line_edge(p, dir_tuple, length, va, vb):
    d = f.direction(dir_tuple); vec = f.vector(d, length); ln = f.line(p, vec)
    return f.edge_curve(va, vb, ln)

p0 = f.cartesian_point((0.0, 0.0, 0.0))
p1 = f.cartesian_point((1.0, 0.0, 0.0))
p2 = f.cartesian_point((1.0, 1.0, 0.0))
p3 = f.cartesian_point((0.0, 1.0, 0.0))
v0 = f.vertex_point(p0); v1 = f.vertex_point(p1)
v2 = f.vertex_point(p2); v3 = f.vertex_point(p3)
e0 = line_edge(p0, (1.0, 0.0, 0.0), 1.0, v0, v1)
e1 = line_edge(p1, (0.0, 1.0, 0.0), 1.0, v1, v2)
e2 = line_edge(p2, (-1.0, 0.0, 0.0), 1.0, v2, v3)
e3 = line_edge(p3, (0.0, -1.0, 0.0), 1.0, v3, v0)
loop = f.edge_loop([
    f.oriented_edge(e0, True), f.oriented_edge(e1, True),
    f.oriented_edge(e2, True), f.oriented_edge(e3, True),
])
face = f.advanced_face([f.face_outer_bound(loop)], plane)
shell = f.open_shell([face])
sbsm = f.shell_based_surface_model([shell])
f.add_product_chain(sbsm)

# A second distinct APPLICATION_CONTEXT record with identical string
# content. The builder's add_product_chain emits the first (#9000);
# this one is unreferenced but present, triggering the transfer-chain
# mismatch the catalog claims.
f._emit_raw("APPLICATION_CONTEXT('mechanical design')")
